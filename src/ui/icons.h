// ============================================================================
//  icons.h — 侧栏导航自研矢量线性图标（v2.18）
//  ---------------------------------------------------------------------------
//  背景：侧栏图标原先取 Segoe MDL2 字形（PickIcon），在部分 Win10/11 机器上
//  字体版本差异导致缺字，渲染成「感叹号/豆腐块」。v2.18 起全部改为自研
//  24×24 网格矢量线稿，GDI+ 抗锯齿直绘，彻底摆脱系统图标字体依赖。
//
//  统一风格纪律（VI-D2 延伸）：
//    * 24×24 设计网格，主形体留 3~4u 呼吸边距
//    * 单一描边宽度 1.9u（随 DPI 缩放），圆头圆角（round cap/join）
//    * 仅线性轮廓 + 极小实心点（视觉配重），不做面填充大色块
//    * 每个模块一个专属语义图形，同族图标共享母形（垃圾桶/文件夹/盾牌…）
// ============================================================================
#pragma once

#include <windows.h>

namespace mz {
namespace ui {
namespace icon {

// 模块 ID → 图标 ID（未知 ID 回落通用「应用方块」图标）
int For(const wchar_t* moduleId);

// 在 box 内居中绘制（取 box 最短边为图标边长；单色，随主题换色）
void Draw(HDC dc, int iconId, const RECT& box, COLORREF color);

} // namespace icon
} // namespace ui
} // namespace mz
